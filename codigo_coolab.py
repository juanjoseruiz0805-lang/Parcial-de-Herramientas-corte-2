from __future__ import annotations
from datetime import date
from enum import Enum


# ---------- Enumeraciones (estados y prioridades) ----------
class EstadoEquipo(Enum):
    OPERATIVO = "OPERATIVO"
    EN_MANTENIMIENTO = "EN_MANTENIMIENTO"
    FUERA_DE_SERVICIO = "FUERA_DE_SERVICIO"


class EstadoOrden(Enum):
    CREADA = "CREADA"
    PROGRAMADA = "PROGRAMADA"
    EN_EJECUCION = "EN_EJECUCION"
    SUSPENDIDA = "SUSPENDIDA"
    FINALIZADA = "FINALIZADA"
    CANCELADA = "CANCELADA"


class Prioridad(Enum):
    BAJA = "BAJA"
    MEDIA = "MEDIA"
    ALTA = "ALTA"
    CRITICA = "CRITICA"


# ---------- Excepción base de reglas de negocio ----------
class ReglaNegocioError(Exception):
    """Se lanza cuando una operación viola una regla de negocio (RN1 a RN9)."""


class Equipo:
    """Máquina industrial. Controla su propio estado (RN7)."""

    def __init__(self, codigo_interno: str, tipo: str, marca: str, modelo: str,
                 fecha_adquisicion: date,
                 estado: EstadoEquipo = EstadoEquipo.OPERATIVO) -> None:
        self.codigo_interno: str = codigo_interno
        self.tipo: str = tipo
        self.marca: str = marca
        self.modelo: str = modelo
        self.fecha_adquisicion: date = fecha_adquisicion
        self.estado: EstadoEquipo = estado

    def esta_operativo(self) -> bool:
        """Informa si el equipo está disponible para operar."""
        return self.estado == EstadoEquipo.OPERATIVO

    def poner_en_mantenimiento(self) -> None:
        """RN7: cuando una orden entra en EN_EJECUCION, el equipo pasa a EN_MANTENIMIENTO."""
        self.estado = EstadoEquipo.EN_MANTENIMIENTO

    def actualizar_estado_final(self, nuevo_estado: EstadoEquipo) -> None:
        """RN7: el supervisor decide si el equipo vuelve a OPERATIVO o pasa a FUERA_DE_SERVICIO."""
        if nuevo_estado not in (EstadoEquipo.OPERATIVO, EstadoEquipo.FUERA_DE_SERVICIO):
            raise ReglaNegocioError(
                "El estado final del equipo debe ser OPERATIVO o FUERA_DE_SERVICIO.")
        self.estado = nuevo_estado

    def __repr__(self) -> str:
        return f"Equipo({self.codigo_interno}, {self.tipo}, {self.estado.value})"


class Actividad:
    """Trabajo realizado dentro de una orden (RN6)."""

    def __init__(self, descripcion: str, horas: float) -> None:
        self.descripcion: str = descripcion
        self.horas: float = horas


class Tecnico:
    """Técnico responsable o de apoyo de una orden."""

    def __init__(self, id_tecnico: int, nombre: str) -> None:
        self.id: int = id_tecnico
        self.nombre: str = nombre
        self.ordenes_responsable: list[OrdenMantenimiento] = []

    def tiene_orden_en_fecha(self, fecha: date) -> bool:
        """RN2: indica si ya es responsable de una orden vigente para esa fecha."""
        vigentes = (EstadoOrden.PROGRAMADA, EstadoOrden.EN_EJECUCION, EstadoOrden.SUSPENDIDA)
        return any(o.fecha_programada == fecha and o.estado in vigentes
                   for o in self.ordenes_responsable)

    def __repr__(self) -> str:
        return f"Tecnico({self.nombre})"


class OrdenMantenimiento:
    """Ciclo de vida de una orden de mantenimiento (máquina de estados de la Parte D)."""

    def __init__(self, numero: int, descripcion: str, prioridad: Prioridad,
                 equipo: Equipo, fecha_creacion: date | None = None) -> None:
        self.numero: int = numero
        self.fecha_creacion: date = fecha_creacion or date.today()
        self.descripcion: str = descripcion
        self.prioridad: Prioridad = prioridad
        self.estado: EstadoOrden = EstadoOrden.CREADA          # estado inicial
        self.fecha_programada: date | None = None
        self.equipo: Equipo = equipo
        self.tecnico_responsable: Tecnico | None = None          # RN1: 0..1 hasta programar
        self.tecnicos_apoyo: list[Tecnico] = []                  # RN1: 0..*
        self.actividades: list[Actividad] = []                   # composición 1 -- 0..*

    # ---------- utilidades internas ----------
    def _exigir_estado(self, evento: str, *permitidos: EstadoOrden) -> None:
        if self.estado not in permitidos:
            raise ReglaNegocioError(
                f"No se puede {evento} una orden en estado {self.estado.value} (RN5).")

    # ---------- eventos de la máquina de estados ----------
    def programar(self, tecnico: Tecnico, fecha: date) -> None:
        """CREADA -> PROGRAMADA. Valida RN4 y RN2."""
        self._exigir_estado("programar", EstadoOrden.CREADA)
        if tecnico is None:
            raise ReglaNegocioError("RN4: la orden necesita un técnico responsable.")
        if fecha < self.fecha_creacion:
            raise ReglaNegocioError("RN4: la fecha programada no puede ser anterior a la de creación.")
        if tecnico.tiene_orden_en_fecha(fecha):
            raise ReglaNegocioError("RN2: el técnico ya tiene una orden programada para esa fecha.")
        self.tecnico_responsable = tecnico
        self.fecha_programada = fecha
        tecnico.ordenes_responsable.append(self)
        self.estado = EstadoOrden.PROGRAMADA

    def iniciar(self) -> None:
        """PROGRAMADA -> EN_EJECUCION. El equipo pasa a EN_MANTENIMIENTO (RN7)."""
        self._exigir_estado("iniciar", EstadoOrden.PROGRAMADA)
        self.estado = EstadoOrden.EN_EJECUCION
        self.equipo.poner_en_mantenimiento()

    def suspender(self) -> None:
        """EN_EJECUCION -> SUSPENDIDA. El equipo sigue EN_MANTENIMIENTO (RN7)."""
        self._exigir_estado("suspender", EstadoOrden.EN_EJECUCION)
        self.estado = EstadoOrden.SUSPENDIDA

    def reanudar(self) -> None:
        """SUSPENDIDA -> EN_EJECUCION."""
        self._exigir_estado("reanudar", EstadoOrden.SUSPENDIDA)
        self.estado = EstadoOrden.EN_EJECUCION

    def cancelar(self) -> None:
        """CREADA, PROGRAMADA o SUSPENDIDA -> CANCELADA. EN_EJECUCION no se cancela (RN5)."""
        self._exigir_estado("cancelar", EstadoOrden.CREADA,
                            EstadoOrden.PROGRAMADA, EstadoOrden.SUSPENDIDA)
        self.estado = EstadoOrden.CANCELADA
        # RN7 / A7: el estado del equipo no se modifica al cancelar.

    # ---------- operaciones de apoyo ----------
    def agregar_tecnico_apoyo(self, tecnico: Tecnico) -> None:
        """RN1: una orden puede tener cero o más técnicos de apoyo."""
        if tecnico is self.tecnico_responsable:
            raise ReglaNegocioError("RN1: el responsable no puede ser también técnico de apoyo.")
        self.tecnicos_apoyo.append(tecnico)

    def registrar_actividad(self, descripcion: str, horas: float) -> None:
        """Registra una actividad realizada (necesaria para finalizar, RN6)."""
        self.actividades.append(Actividad(descripcion, horas))

    def horas_totales(self) -> float:
        return sum(a.horas for a in self.actividades)

    def __repr__(self) -> str:
        return f"Orden #{self.numero} [{self.estado.value}] equipo={self.equipo.codigo_interno}"


